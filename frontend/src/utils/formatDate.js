// Small shared date-formatting utility.
// Returns a human-readable string like "Aug 29, 2026, 19:04",
// or "-" for null/undefined/invalid values.

export default function formatDate(value) {
  if (!value) return "-";

  const date = new Date(value);

  if (Number.isNaN(date.getTime())) return "-";

  return new Intl.DateTimeFormat("en-GB", {
    day: "numeric",
    month: "short",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
    hour12: false,
  }).format(date);
}
